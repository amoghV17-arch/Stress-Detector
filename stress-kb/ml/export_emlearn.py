#!/usr/bin/env python3
"""export_emlearn.py — Exports trained scikit-learn model to C header via emlearn.
Source of truth per docs/FEATURES.md and docs/MILESTONES.md M6.
Outputs:
- firmware/stresskb/model/stress_model.h (pure C tree evaluation code)
- firmware/stresskb/model/model_config.h (feature indices, global baselines, classes)
- firmware/host_tests/test_model_data.h (golden test vectors for C host agreement test)
- ml/export/heldout/ (held-out sessions and predictions)
"""

import os
import sys
import json
import math
import joblib
import numpy as np
from typing import List, Dict, Any

import emlearn
from train import transform_features, load_data

def export_model(model_path: str = "ml/model_rf.joblib",
                 feat_sel_path: str = "ml/feature_selection.json",
                 data_dir: str = "ml/data/synthetic",
                 firmware_dir: str = "firmware/stresskb",
                 host_test_dir: str = "firmware/host_tests",
                 export_heldout_dir: str = "ml/export/heldout"):

    os.makedirs(os.path.join(firmware_dir, "model"), exist_ok=True)
    os.makedirs(host_test_dir, exist_ok=True)
    os.makedirs(export_heldout_dir, exist_ok=True)

    print(f"Loading trained model from {model_path}...")
    clf = joblib.load(model_path)

    with open(feat_sel_path, 'r', encoding='utf-8') as fp:
        feat_meta = json.load(fp)

    selected_indices = feat_meta['feature_indices_0indexed']
    n_features = len(selected_indices)
    classes = feat_meta['classes']
    n_classes = len(classes)
    all_mu = feat_meta['all_global_baseline']['mu']
    all_sd = feat_meta['all_global_baseline']['sd']

    # Compute effective sd: sd_eff = max(sd, 0.1 * |mu|, 1e-3)
    all_sd_eff = [max(float(all_sd[i]), 0.1 * abs(float(all_mu[i])), 1e-3) for i in range(18)]

    # 1. Convert to C header using emlearn
    print("Converting model to C code with emlearn...")
    cmodel = emlearn.convert(clf, dtype='float')
    c_code = cmodel.save(name='stress_model')

    model_header_path = os.path.join(firmware_dir, "model", "stress_model.h")
    with open(model_header_path, 'w', encoding='utf-8') as fp:
        fp.write("// stress_model.h — Generated TinyML inference code via emlearn\n")
        fp.write("// DO NOT EDIT DIRECTLY. Generated by ml/export_emlearn.py\n\n")
        fp.write(c_code)
    print(f"Saved {model_header_path} ({len(c_code)} bytes)")

    # 2. Generate model_config.h
    config_header_path = os.path.join(firmware_dir, "model", "model_config.h")
    config_lines = [
        "#pragma once",
        "",
        "// model_config.h — StressKB TinyML Model Configuration and Baseline Constants",
        "// Generated by ml/export_emlearn.py per docs/FEATURES.md",
        "",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        f"#define MODEL_N_FEATURES {n_features}",
        f"#define MODEL_N_CLASSES {n_classes}",
        f"#define MODEL_N_TREES {len(clf.estimators_)}",
        "",
        "// 0-indexed indices into WindowFeatures.f[18] selected for model inference",
        f"static const uint8_t MODEL_FEATURE_INDICES[{n_features}] = {{"
        + ", ".join(str(idx) for idx in selected_indices) + "};",
        "",
        "// Selected feature names",
        f"static const char* const MODEL_FEATURE_NAMES[{n_features}] = {{"
        + ", ".join(f'"{name}"' for name in feat_meta['selected_features']) + "};",
        "",
        "// Global baseline defaults for all 18 features (used when user has no CAL baseline)",
        "static const float MODEL_ALL_GLOBAL_MU[18] = {",
        "    " + ", ".join(f"{all_mu[i]:.6f}f" for i in range(18)),
        "};",
        "",
        "static const float MODEL_ALL_GLOBAL_SD_EFF[18] = {",
        "    " + ", ".join(f"{all_sd_eff[i]:.6f}f" for i in range(18)),
        "};",
        "",
        "// Class names",
        f"static const char* const MODEL_CLASS_NAMES[{n_classes}] = {{"
        + ", ".join(f'"{c}"' for c in classes) + "};",
        ""
    ]

    with open(config_header_path, 'w', encoding='utf-8') as fp:
        fp.write("\n".join(config_lines) + "\n")
    print(f"Saved {config_header_path}")

    # 3. Generate test vectors for host test agreement (held-out participant u10)
    print("Generating held-out test vectors for C host agreement testing...")
    dataset, _ = load_data(data_dir)
    groups = dataset['groups']
    X = dataset['X']
    user_baseline = dataset['user_baseline']

    # Select held-out participant (e.g. u10)
    heldout_pid = "u10" if "u10" in set(groups) else groups[-1]
    heldout_mask = (groups == heldout_pid)
    X_heldout = X[heldout_mask][:, selected_indices]

    sk_preds = clf.predict(X_heldout)
    sk_probs = clf.predict_proba(X_heldout)

    # Export held-out JSON for verification
    heldout_records = []
    for i in range(len(X_heldout)):
        record = {
            "window_idx": i,
            "z_features": [float(val) for val in X_heldout[i]],
            "expected_class": int(sk_preds[i]),
            "expected_probs": [float(p) for p in sk_probs[i]]
        }
        heldout_records.append(record)

    heldout_json_path = os.path.join(export_heldout_dir, f"{heldout_pid}_predictions.json")
    with open(heldout_json_path, 'w', encoding='utf-8') as fp:
        json.dump(heldout_records, fp, indent=2)
    print(f"Saved held-out test predictions to {heldout_json_path} ({len(heldout_records)} windows)")

    # 4. Write C test vectors header for firmware host test
    test_data_header_path = os.path.join(host_test_dir, "test_model_data.h")
    test_lines = [
        "#pragma once",
        "",
        "// test_model_data.h — Golden test vectors for C vs scikit-learn agreement verification",
        "// Generated by ml/export_emlearn.py",
        "",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "struct ModelTestCase {",
        f"    float z[{n_features}];",
        f"    float expected_probs[{n_classes}];",
        "    int expected_class;",
        "};",
        "",
        f"#define N_MODEL_TEST_CASES {len(heldout_records)}",
        "",
        f"static const ModelTestCase MODEL_TEST_CASES[N_MODEL_TEST_CASES] = {{"
    ]

    for rec in heldout_records:
        z_str = ", ".join(f"{val:.6f}f" for val in rec['z_features'])
        p_str = ", ".join(f"{p:.6f}f" for p in rec['expected_probs'])
        test_lines.append(f"    {{ {{{z_str}}}, {{{p_str}}}, {rec['expected_class']} }},")

    test_lines.append("};")
    test_lines.append("")

    with open(test_data_header_path, 'w', encoding='utf-8') as fp:
        fp.write("\n".join(test_lines) + "\n")
    print(f"Saved host test vectors to {test_data_header_path}")

    return {
        "model_header": model_header_path,
        "config_header": config_header_path,
        "test_header": test_data_header_path,
        "heldout_json": heldout_json_path,
        "n_test_cases": len(heldout_records)
    }

if __name__ == "__main__":
    export_model()
